namespace pondex.UI;

public sealed class HelpDialog : Form
{
    public HelpDialog()
    {
        Text = "pondex ヘルプ";
        AutoScaleMode = AutoScaleMode.Dpi;
        StartPosition = FormStartPosition.CenterParent;
        FormBorderStyle = FormBorderStyle.Sizable;
        MinimumSize = new Size(620, 480);
        ClientSize = new Size(760, 620);
        MaximizeBox = true;
        MinimizeBox = false;
        DpiWindowHelper.Attach(this);

        var text = new RichTextBox
        {
            Dock = DockStyle.Fill,
            ReadOnly = true,
            BorderStyle = BorderStyle.None,
            BackColor = SystemColors.Window,
            Font = UiTheme.CreateFont(10F),
            Text = HelpText,
            DetectUrls = false,
            TabStop = false
        };
        var content = new Panel { Dock = DockStyle.Fill, Padding = new Padding(24, 18, 24, 12), BackColor = SystemColors.Window };
        content.Controls.Add(text);
        var closeButton = new Button
        {
            Text = "閉じる",
            Dock = DockStyle.Right,
            Width = 110,
            DialogResult = DialogResult.OK
        };
        var footer = new Panel { Dock = DockStyle.Bottom, Height = 52, Padding = new Padding(8) };
        footer.Controls.Add(closeButton);
        Controls.Add(content);
        Controls.Add(footer);
        AcceptButton = closeButton;
        CancelButton = closeButton;
    }

    private const string HelpText = """
        基本操作

        ・「音源追加」またはドラッグ＆ドロップで音源を追加します。
        ・対応形式はWAV、MP3、Ogg Vorbis、Ogg Opus、FLAC、AIFF、M4A、AAC、WMAです。
          FLAC／M4A／AAC／WMAはWindowsのMedia Foundationで読み込むため、PC側の対応状況によっては再生できない場合があります。
        ・各カードの「詳細」→「ファイル」→「参照…」で、登録を残したまま音声ファイルだけ差し替えられます。
        ・「詳細」の「この音源を削除…」では、音声ファイルを残したままプロジェクトから登録を削除します。最後のグループ音源を削除した場合、そのグループ専用設定も確認後に削除されます。
        ・再生ボタン、または設定したキーで再生します。
        ・同じキーを複数音源へ設定すると、1回のキー操作でまとめて同時再生できます。同じグループ内でも同時再生されます。
        ・Alt＋音源の設定キーで、同じGroupの他音源を即時停止して切り替えます。Group専用キーは対象外です。
        ・Shift＋設定キーでその音源を停止します。Ctrl＋Rは全音源を停止します。
        ・名前、キー、グループ、メモなどはEnterで確定、Escで変更を取り消せます。
        ・キーには空白を使えません。A、2、F1などのキー名を空白なしで指定してください。解釈できない値は編集終了時に解除されます。
        ・Ctrl＋Sで保存、Ctrl＋Shift＋Sで名前を付けて保存、Ctrl＋Oで開く、Ctrl＋Nで新規作成できます。
        ・設定や確認ダイアログを開いている間は、通常の再生キーを受け付けません。

        音源一覧

        ・「設定」→「音源一覧の列数」で1～8列を選べます。
        ・「設定」→「画面全体を暗い配色にする」で、ライト／ダーク表示を切り替えられます。設定はプロジェクトへ保存されます。
        ・ダークモードではタブの余白やボタン枠も暗い配色に揃え、対応するWindowsではタイトルバー・スクロールバーも切り替わります。
        ・指定列数がウィンドウ幅に収まらない場合は、操作不能を防ぐため自動的に列数を減らします。
        ・「操作」→「並び替え…」で、音源を選び「上へ」「下へ」「先頭へ」「末尾へ」、または移動先の番号を指定して並び替えられます。「適用」で確定し、「キャンセル」で元の順番を保ちます。
        ・複数列では一覧の順に左から右、次の行へ表示します。並び替え画面ではAlt＋↑／↓でも移動できます。再生中の音や開いている詳細はそのままです。
        ・一覧のホイール移動は滑らかに流れて止まり、スクロールバーのつまみを動かしたときは即座に追従します。音量スライダーや数値欄の上では、ホイールでその値を調整できます。

        音量

        ・通常の音量上限は100%です。音源の「再生調整…」で限界突破を許可すると、その音源だけ200%まで使えます。MASTERは100%までです。
        ・音量バーはマウスホイール、矢印キー、ドラッグで変更でき、横の数値欄へ直接入力することもできます。
        ・限界突破をOFFにすると、100%を超えていた音量も100%以内へ戻ります。許可設定は音源ごとに保存します。
        ・音量の数値欄を右クリックすると100%へ戻せます。100%超で音割れする場合は音量を下げてください。
        ・音源の音量バーを右クリックすると、Fade Outの秒数を使って指定音量まで変化します。

        Pan／Pitch

        ・Panは -100で左、0で中央、+100で右です。Pan欄を右クリックすると0へ戻ります。
        ・Pitchは0.50～2.00倍です。1.00が元の高さです。
        ・「詳細」→「再生調整…」から、再生を止めずに速度・Pitch・Panを変更できます。音源ごとに1枚ずつ開き、メイン画面へ戻って再生・停止できます。
        ・速度・Pitch・Panはスライダーで調整でき、横の数値入力とも連動します。スライダーの右クリックで、その項目だけ標準値に戻せます。
        ・速度は0.50～2.00倍で、速度に合わせて音程も変わります。Pitchは別の音程補正です。変更はプロジェクトへ保存され、次回の再生にも適用されます。

        Fade In／Fade Out

        ・Fade Inは、次回の再生開始時に無音から設定音量まで指定秒数で上げます。
        ・「設定」の「通常の停止操作でFade Outを使う」がONなら、停止ボタン、Shift＋キー、グループ停止、停止トリガで、指定秒数をかけて下げてから停止します。
        ・停止時フェードをOFFにすると、通常の停止操作も即時停止になります。
        ・「全停止でも音源ごとのFade Outを使う」がONなら、全停止でもFade Out設定のある音源はフェード後に停止します。OFFなら即時停止します。
        ・全停止時フェードは通常停止時フェードとは別に設定できます。Ctrl＋R、操作メニュー、常設ボタンの全停止すべてに適用されます。
        ・チェックをONにした時点で秒数が0なら、自動的に1.00秒へ設定します。

        ループ開始（秒）

        初回は0秒から再生します。音源末尾まで再生したあと、ループで戻る位置を秒単位で指定します。
        0、または音源の長さ以上の値なら先頭へ戻ります。
        旧版プロジェクトにsample値がある場合も、その値を互換用として引き続き読み込めます。

        グループ

        グループは音源の分類と一括操作に使用します。同じグループ内の音源も同時再生できます。
        ・「操作」→「グループキー…」で、グループ専用のキーを複数登録できます。
        ・登録キーでグループ内の全音源を同時再生し、Shift＋登録キーでまとめて停止します。
        ・「操作」→「ミュート」は、上部のミュートチェックと同じ状態を切り替えます。

        イベントトリガ

        指定時刻、ストップウォッチ経過時間、音源終了、音源経過時間を条件として、
        対象音源の再生・停止・一時停止を自動実行できます。
        ・一覧の「有効」チェックから、その場で有効／無効を切り替えられます。
        ・発火しても設定は無効になりません。同じ条件の間は一度だけ発火し、時計のリセットや音源の再再生で再び待機します。
        ・時刻条件はアプリ起動後に指定時刻を通過したとき発火します。起動前の時刻を遡って発火せず、日をまたぐ0時指定にも対応します。
        ・対象にグループを選ぶと、同じグループの全音源へ再生・停止・一時停止を実行できます。
        ・グループ対象の再生では、グループ内の全音源を同時再生します。
        ・音源の再生経過時間は、一時停止中には進みません。速度を変えても、実際に再生している秒数で数えます。
        ・参照先が見つからないイベントは警告を表示します。編集時に別の音源へ自動変更せず、対象を選び直してから確定します。

        保存

        ・タイトル末尾の「*」は未保存の変更がある印です。保存後は消えます。
        ・終了時の保存確認は未保存の変更がある場合だけ表示されます。
        ・保存中に音量などを変更した場合は未保存の印が残ります。再保存するまで、保存完了を理由とする終了・切替は中止します。
        ・バックアップ整理だけが失敗した場合、本体は保存済みです。ステータスとログに表示された復旧用バックアップを確認してください。
        ・表示・出力設定は各プロジェクト、履歴は実行フォルダのData、ログはLogsに保存します。書き込み不可ならユーザーフォルダ、一時フォルダへ退避します。

        誤変更防止の編集ロック

        画面下の「編集ロック」からロックするできます。音源追加/削除、イベント編集、出力先変更、プロジェクト切替も防ぎます。
        再生・停止・一時停止・緊急停止・時計/SW操作・保存は使えます。開いている調整画面は閉じます。
        解除は「ロック: ON」を開いて「ロックを解除」を選びます。再起動時は解除状態で始まります。

        緊急強制停止

        画面下の「緊急停止」または「操作」→「緊急停止」は、再生中・一時停止中・フェード中と準備中の再生を確認画面なしで停止します。
        自動イベントは「イベント再開」まで休止し、手動再生は可能です。SW計測は継続します。実行済み・休止中に通過した条件は再開で遡って発火しません。SWの「リセット」でSW条件を再び発火可能にします。
        出力異常時は停止します。Windows既定も選択時の物理出力に固定し、既定先の変更検出で停止します。設定で出力先を選び直してください。
        部分読込で設定を復元できなかった場合、元ファイルへ上書きせず別名保存してください。
        通常の全停止とCtrl+Rには従来のフェード設定が適用されます。緊急停止には専用キーを割り当てていません。

        動作診断

        「操作」→「動作診断…」から、対応音声形式、音声出力、ループ、キーフック、DPI設定を確認できます。
        短いテスト音が鳴り、結果はLogsフォルダへ保存されます。
        「設定」の「詳細ログ」をONにすると、再生要求・準備時間・停止理由・出力先・音源設定などを記録します。OKですぐ反映し、プロジェクトに保存されます。既定はOFFです。
        ログは記録日ごとにLogsへ随時保存します。混雑時はDEBUGから優先して破棄し、破棄数を記録します。詳細ログには音源のパスなどが含まれるため、共有前に確認してください。
        「操作」→「再生開始を計測」は必要なときだけONにします。prepare_msはデコーダ・パイプライン準備、start_msは再生開始処理までの累計時間です。
        attemptは計測開始後の音源ごとの準備要求回数です。実際のスピーカー出音遅延ではなく、計測OFF時は計測ログを追加しません。
        本番前に、使用するPC・音声デバイス・音源で通し確認してください。
        """;
}
